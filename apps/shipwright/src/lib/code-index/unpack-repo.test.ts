import assert from "node:assert/strict";
import { Readable } from "node:stream";
import { test } from "node:test";
import { gzipSync } from "node:zlib";
import { pack, type Header } from "tar-stream";
import { isIgnoredPath, unpackRepoTarball } from "./unpack-repo.ts";

type Entry = { header: Partial<Header> & Pick<Header, "name">; body?: string | Uint8Array };

// Builds a small .tar.gz in memory, the same shape GitHub sends (everything under "owner-repo-sha/").
async function makeTarball(entries: Entry[]): Promise<Readable> {
  const archive = pack();
  const chunks: Buffer[] = [];
  archive.on("data", (chunk: unknown) => chunks.push(Buffer.from(chunk as Uint8Array)));
  const finished = new Promise<void>((resolve, reject) => {
    archive.on("end", resolve);
    archive.on("error", reject);
  });
  for (const { header, body } of entries) {
    await new Promise<void>((resolve, reject) => {
      const done = (error?: Error | null) => (error ? reject(error) : resolve());
      if (body === undefined) archive.entry(header, done);
      else archive.entry(header, body, done);
    });
  }
  archive.finalize();
  await finished;
  return Readable.from([gzipSync(Buffer.concat(chunks))]);
}

test("a normal file is kept; unsafe, linked, ignored, big and binary files are skipped with the right reason", async () => {
  const tarball = await makeTarball([
    { header: { name: "acme-shop-abc123/", type: "directory" } },
    { header: { name: "acme-shop-abc123/src/app.ts" }, body: "export const answer = 42;\n" },
    { header: { name: "acme-shop-abc123/.env.local" }, body: "STRIPE_KEY=sk_live_oops\n" },
    { header: { name: "../evil.ts" }, body: "process.exit(1)" },
    { header: { name: "acme-shop-abc123/link.ts", type: "symlink", linkname: "/etc/passwd" } },
    { header: { name: "acme-shop-abc123/node_modules/left-pad/index.js" }, body: "module.exports = 1;" },
    { header: { name: "acme-shop-abc123/src/huge.ts" }, body: "x".repeat(400 * 1024) },
    { header: { name: "acme-shop-abc123/src/data.ts" }, body: Buffer.from([0x61, 0x00, 0x62]) },
    { header: { name: "acme-shop-abc123/src/db.types.ts" }, body: "// @generated by supabase\nexport type Db = {};\n" },
  ]);

  const result = await unpackRepoTarball(tarball);

  // The first folder is stripped, and .env files are kept on purpose.
  assert.deepEqual(result.files.map((file) => file.path).sort(), [".env.local", "src/app.ts"]);
  const app = result.files.find((file) => file.path === "src/app.ts");
  assert.equal(app?.text, "export const answer = 42;\n");
  assert.equal(app?.sizeBytes, 26);
  assert.equal(result.totalBytes, result.files.reduce((sum, file) => sum + file.sizeBytes, 0));

  assert.deepEqual(result.skipped, {
    ignored_path: 1, // node_modules
    too_big: 1,
    binary: 1,
    not_a_file: 2, // the folder and the symlink
    unsafe_path: 1,
    limit_reached: 0,
    generated: 1,
  });
});

test("a corrupt download throws instead of returning half a repo", async () => {
  await assert.rejects(unpackRepoTarball(Readable.from([Buffer.from("this is not a gzip file")])));
});

test("ignored paths: folders at any depth, lockfiles, images, fonts, minified files; .env stays", () => {
  for (const path of [
    "node_modules/a/index.js", "apps/web/.next/server.js", "packages/x/dist/index.js", "vendor/lib.php", "coverage/lcov.info",
    "pnpm-lock.yaml", "package-lock.json", "yarn.lock", "bun.lock", "bun.lockb", "public/logo.PNG", "fonts/a.woff2",
    "public/app.min.js", "app.js.map", "demo.mp4", "backup.zip", ".DS_Store",
  ]) {
    assert.equal(isIgnoredPath(path), true, path);
  }
  for (const path of [".env", ".env.example", "src/build.ts", "src/lib/out.ts", "supabase/migrations/1.sql", "README.md"]) {
    assert.equal(isIgnoredPath(path), false, path);
  }
});

// Regenerates packages/db/src/database.types.ts from the LOCAL database (public + server schemas).
// Run: pnpm db:types   (the local stack must be running: pnpm db:start)
//
// Safety: a plain `supabase gen types > file` would leave an EMPTY file behind if the command fails. Here the file is replaced
// only when the CLI succeeded and its output really is the types, so a failed run changes nothing.
// It only ever talks to the local stack (the default); there is no remote target in this script.
import { spawnSync } from "node:child_process";
import { renameSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "packages/db/src/database.types.ts");

const result = spawnSync("pnpm", ["exec", "supabase", "gen", "types", "typescript", "--schema", "public,server"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 20 * 1024 * 1024,
});

if (result.status !== 0 || !result.stdout.includes("export type Database")) {
  console.error("Could not generate the types, so nothing was changed. Is the local stack running (pnpm db:start)?");
  console.error(result.stderr.split("\n").slice(-6).join("\n"));
  process.exit(1);
}

const header = [
  "// GENERATED by `pnpm db:types` from the local database (schemas: public, server). Do not edit by hand.",
  "// After changing a migration: pnpm db:reset, then pnpm db:types, then commit this file.",
  "",
].join("\n");

const temporary = `${target}.tmp`;
writeFileSync(temporary, `${header}${result.stdout}`);
renameSync(temporary, target);
console.log(`Wrote ${path.relative(root, target)} (${result.stdout.split("\n").length} lines).`);
